"""Audit maintained sources and the prepared distribution without changing files."""
import argparse
import json
from pathlib import Path
import re
import sys
import xml.etree.ElementTree as ET

SOURCE_EXTENSIONS = {'.cpp', '.h', '.qml', '.py', '.ps1', '.rc', '.ino', '.yml', '.yaml'}
TEXT_EXTENSIONS = SOURCE_EXTENSIONS | {'.md', '.json', '.txt', '.svg', '.qrc'}
OWNED_FOLDERS = ('src', 'qml', 'private', 'tests', 'core', 'scripts', 'tools', 'docs', 'examples', 'scenarios', 'assets', '.github', 'sdk', 'SLX_ResilienceLab_Valve')
ITALIAN = re.compile(r'\b(?:guasto|guasti|misure|sensore|sensori|valvola|richiesta|ripristina|esegui|confronto|scenari|cartella|principale|riserva|scollegato|certificato|dimostratore|utilizzata)\b', re.I)
PERSONAL_PATH = re.compile(r'(?:[A-Z]:[/\\]Users[/\\]|/home/|/Users/)', re.I)
DRAFT = re.compile(r'\b(?:TO' + r'DO|FIX' + r'ME|internal note|note interne|as an ' + r'AI|generated by ' + r'AI|chat' + r'gpt|co' + r'dex|open' + r'ai)\b', re.I)
SECRET = re.compile(r'(?:gh[pousr]_[A-Za-z0-9]{30,}|github_pat_[A-Za-z0-9_]{30,}|-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----)')


def audit(root, distribution=False, allow_git=False):
    errors, checked = [], []
    if distribution:
        forbidden = ('private', 'tests', 'workspace', 'build') + (() if allow_git else ('.git',))
        for folder in forbidden:
            if (root/folder).exists():
                errors.append(f'Forbidden distribution directory: {folder}')
    paths = []
    for name in OWNED_FOLDERS:
        folder = root/name
        if folder.exists():
            paths.extend(p for p in folder.rglob('*') if p.is_file())
    paths.extend(p for p in root.iterdir() if p.is_file())
    for path in sorted(set(paths)):
        relative = path.relative_to(root).as_posix()
        if '__pycache__' in path.parts:
            errors.append(f'Python cache included: {relative}')
            continue
        if path.stat().st_size >= 100*1024*1024:
            errors.append(f'File exceeds source Git size limit: {relative}')
        # Original asset package and third-party legal texts retain their own attribution.
        if path.suffix.lower() not in TEXT_EXTENSIONS and path.name not in ('CMakeLists.txt', '.gitignore', '.gitattributes', '.clang-format'):
            continue
        text = path.read_text(encoding='utf-8-sig')
        checked.append(relative)
        if path.name not in ('LICENSE', 'THIRD_PARTY_NOTICES.md', 'THIRD_PARTY_SOURCE.md'):
            if path.suffix.lower() == '.json':
                data = json.loads(text)
                if relative.startswith('scenarios/') and 'copyright' not in data.get('_meta', {}):
                    errors.append(f'Missing JSON attribution: {relative}')
            elif 'copyright' not in text[:700].lower() and relative != 'SLX_ResilienceLab_Valve/scene/asset_manifest.json':
                errors.append(f'Missing attribution header: {relative}')
        # The scanner's own expressions are definitions, not product text.
        scan = text if relative != 'tools/audit-release.py' else '\n'.join(line for line in text.splitlines() if not line.startswith(('ITALIAN =', 'PERSONAL_PATH =', 'DRAFT =', 'SECRET =')))
        for name,pattern in [('draft/assistant text', DRAFT), ('personal path', PERSONAL_PATH), ('credential', SECRET), ('non-English product text', ITALIAN)]:
            if pattern.search(scan): errors.append(f'{name}: {relative}')
        if '\ufffd' in text: errors.append(f'Invalid replacement character: {relative}')
    resources = root/'resources.qrc'
    if resources.exists():
        for node in ET.parse(resources).iter('file'):
            if not (root/(node.text or '')).is_file(): errors.append('Missing resource: '+str(node.text))
    if distribution:
        sdk = root/'sdk/windows-mingw'
        for name in ('SiliconLogiX.ResilienceLab.Core.dll', 'SiliconLogiX.ResilienceLab.Core.dll.a', 'ABI.txt'):
            if not (sdk/name).is_file(): errors.append('Missing compiled SDK: '+name)
    return {'schema':'siliconlogix.source-audit.v1', 'checked_files':len(checked), 'distribution':distribution,
            'copyright':'Copyright (c) 2026 Marco Pezzullo / Silicon LogiX',
    'scope':'Maintained project and asset authoring text; third-party legal material retains its original attribution.',
            'passed':not errors, 'errors':errors}


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument('--distribution', action='store_true')
    parser.add_argument('--allow-git', action='store_true', help='Allow Git metadata in a newly initialized public checkout or CI')
    parser.add_argument('--report', type=Path)
    args=parser.parse_args()
    result=audit(args.root.resolve(),args.distribution,args.allow_git)
    if args.report:
        args.report.parent.mkdir(parents=True,exist_ok=True)
        args.report.write_text(json.dumps(result,indent=2)+'\n',encoding='utf-8')
    print(json.dumps(result,indent=2))
    return 0 if result['passed'] else 1


if __name__=='__main__':
    sys.exit(main())
